#!/bin/bash
set -eo pipefail

# ==========================================
# DataDock — Multi-Environment Deployment Script
# Diadaptasi dari template Standard CI/CD (template Standard CI/CD lab).
#
# Perbedaan dari template (lihat DEPLOYMENT.md):
#   - Engine database (PostgreSQL/MariaDB/MongoDB) adalah instance bare-metal yang SUDAH ADA di server;
#     script ini tidak men-deploy engine. Control plane menjangkaunya lewat host.docker.internal / host:port.
#   - Akun admin hak minimum dibuat/diselaraskan dengan akun root instance (opsional, dari CI/CD variable
#     DATADOCK_ROOT_ENV_FILE); kredensial root tidak disimpan di server dan tidak masuk ke control plane.
#   - Control plane butuh direktori data (SQLite) dan direktori backup di host.
#   - Instance dev/stage memakai TENANT_PREFIX dan CI_VARIABLES_ENABLED=false supaya tidak
#     bentrok dengan production di instance database maupun di CI/CD variable GitLab.
#   - Perintah `test`: engine sementara (container) + test terhadap engine asli.
#
# Perintah: build | deploy | test | test-cleanup
# ==========================================

# Load environment variables generated by .gitlab-ci.yml
if [ -f deploy.env ]; then
    source deploy.env
fi

# ==========================================
# Configuration & Dynamic Naming
# ==========================================

ENV_BASE_DIR="${ENV_BASE_DIR:-/opt/environments}"
PORT_RANGE_START=3001
PORT_RANGE_END=3050
CLOUDFLARED_TUNNEL_IMAGE="cloudflare/cloudflared:latest"
PROJECT_NAME="${CI_PROJECT_NAME:-datadock}"
IMAGE_TAG="${CI_COMMIT_SHORT_SHA:-latest}"
ROOT_DOMAIN="iimlab.id"
APP_DIR="control-plane"
TEST_ENGINES_COMPOSE="deploy/test-engines.compose.yml"
IMAGE_NAME="${PROJECT_NAME}:${IMAGE_TAG}"
TEST_STACK="ci_${PROJECT_NAME}_${CI_PIPELINE_ID:-local}"

# ==========================================
# Helper Functions
# ==========================================
log_info() { echo -e "\n✅ [INFO] $1" >&2; }
log_warn() { echo -e "\n⚠️  [WARN] $1" >&2; }
log_error() { echo -e "\n❌ [ERROR] $1" >&2; }

random_secret() { head -c 24 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 28; }

# Baca satu nilai dari file KEY=VALUE tanpa mengeksekusinya; key yang tidak ada → string kosong (bukan error)
env_get() { { grep -E "^$2=" "$1" || true; } | tail -n 1 | cut -d= -f2- | sed -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/"; }

# ==========================================
# Environment Resolution (deploy)
# ==========================================

resolve_environment() {
    # 1. Tentukan Environment Type & Ambil Tunnel ID dari Variable GitLab
    case "$DEPLOY_ENV" in
        dev)
            TUNNEL_ID="${DEV_TUNNEL_ID}"
            TUNNEL_SERVICE_NAME="dev_tunnel"
            ;;
        stage)
            TUNNEL_ID="${STAGE_TUNNEL_ID}"
            TUNNEL_SERVICE_NAME="stage_tunnel"
            ;;
        prod)
            TUNNEL_ID="${PROD_TUNNEL_ID}"
            TUNNEL_SERVICE_NAME="prod_tunnel"
            ;;
        *)
            log_error "Unknown environment: $DEPLOY_ENV"
            exit 1
            ;;
    esac

    # 2. Logika Penamaan Subdomain & Container (sama dengan template)
    CLEAN_BRANCH=$(echo "$CI_COMMIT_BRANCH" | tr '[:upper:]' '[:lower:]')

    if [ "$DEPLOY_ENV" == "prod" ]; then
        SUBDOMAIN="${PROD_SUBDOMAIN_OVERRIDE:-$PROJECT_NAME}"
        CONTAINER_NAME="prod_${PROJECT_NAME}"
        TENANT_PREFIX=""
        CI_VARIABLES_ENABLED="true"
    elif [ "$DEPLOY_ENV" == "stage" ]; then
        SUBDOMAIN="stage_${PROJECT_NAME}"
        CONTAINER_NAME="stage_${PROJECT_NAME}"
        TENANT_PREFIX="s_"
        CI_VARIABLES_ENABLED="false"
    else
        SUBDOMAIN="${CLEAN_BRANCH}_${PROJECT_NAME}"
        CONTAINER_NAME="${CLEAN_BRANCH}_${PROJECT_NAME}"
        # Satu prefiks per branch: instance dev berbagi instance database tanpa bentrok nama
        TENANT_PREFIX="d$(echo -n "$CLEAN_BRANCH" | md5sum | cut -c1-6)_"
        CI_VARIABLES_ENABLED="false"
    fi

    FULL_HOSTNAME="${SUBDOMAIN}.${ROOT_DOMAIN}"

    # Environment paths
    ENV_DIR="${ENV_BASE_DIR}/${DEPLOY_ENV}"
    CONFIG_DIR="${ENV_DIR}/configs"
    CLOUDFLARED_DIR="${ENV_DIR}/cloudflared"
    DOCKER_COMPOSE_FILE="${ENV_DIR}/docker-compose.yml"
    CLOUDFLARED_CONFIG="${CLOUDFLARED_DIR}/config.yml"
    APP_ENV_FILE="${CONFIG_DIR}/.env.${CONTAINER_NAME}"
    DATA_DIR="${ENV_DIR}/data/${CONTAINER_NAME}"
}

# ==========================================
# Port Management Logic (Stateless) — diadaptasi dari template
# ==========================================

# Port host di semua docker-compose.yml di ENV_BASE_DIR (termasuk service yang sedang mati), kecuali service $1.
# Bentuk port: "HOST:CONTAINER" atau "IP:HOST:CONTAINER"; baris lain (volume, extra_hosts) tidak numerik.
compose_ports() {
    local f
    for f in "$ENV_BASE_DIR"/*/docker-compose.yml; do
        [ -f "$f" ] || continue
        awk -v ex="$1" '
            /^[^ #]/ { svc = "" }
            /^  [^ #][^ ]*:[[:space:]]*$/ { svc = $1; sub(/:$/, "", svc) }
            svc != ex && /^[[:space:]]+-[[:space:]]/ {
                v = $0; sub(/^[[:space:]]+-[[:space:]]*/, "", v); gsub(/["'"'"']/, "", v)
                n = split(v, p, ":"); h = (n == 3 ? p[2] : p[1])
                if (n >= 2 && h ~ /^[0-9]+$/) print h
            }' "$f"
    done
}

# Port host milik container di daemon Docker (binding yang dikonfigurasi + yang sedang aktif), kecuali container $1.
# Mencakup container di luar /opt/environments.
docker_ports() {
    docker ps -aq | xargs -r docker inspect -f \
        '{{.Name}} {{range $p, $b := .HostConfig.PortBindings}}{{range $b}}{{.HostPort}} {{end}}{{end}}{{range $p, $b := .NetworkSettings.Ports}}{{range $b}}{{.HostPort}} {{end}}{{end}}' \
        2>/dev/null | awk -v ex="/$1" '$1 != ex { for (i = 2; i <= NF; i++) if ($i ~ /^[0-9]+$/) print $i }'
}

# Port TCP yang sedang LISTEN di network namespace host, termasuk proses non-Docker. Dibaca dari /proc/net/tcp
# lewat container --network host, karena job deploy bisa berjalan di container yang tidak melihat port host.
host_listen_ports() {
    local raw
    raw=$(docker run --rm --network host --entrypoint cat "${IMAGE_NAME}" /proc/net/tcp /proc/net/tcp6 2>/dev/null) || raw=""
    if [ -n "$raw" ]; then
        # Kolom 2 = alamat:port lokal (hex), kolom 4 = state (0A = LISTEN)
        echo "$raw" | awk '$4 == "0A" { split($2, a, ":"); print a[2] }' | while read -r hex; do echo $((16#$hex)); done
    elif command -v ss >/dev/null 2>&1; then
        ss -Htln | awk '{ n = split($4, a, ":"); print a[n] }'
    else
        log_warn "Tidak bisa membaca port LISTEN di host; hanya port dari Docker dan file compose yang dicek"
    fi
}

get_assigned_port() {
    local existing_port="" used own

    if [ -f "$DOCKER_COMPOSE_FILE" ]; then
        # Coba ambil port dari konfigurasi yang sudah ada
        existing_port=$(grep -A 40 "container_name: ${CONTAINER_NAME}$" "$DOCKER_COMPOSE_FILE" | grep -m 1 -oP ' - "\K[0-9]+(?=:)' || true)
    fi

    # Port milik container ini sendiri (deploy ulang) tidak dihitung sebagai bentrok
    own=$(docker inspect -f '{{range $p, $b := .NetworkSettings.Ports}}{{range $b}}{{.HostPort}} {{end}}{{end}}' "${CONTAINER_NAME}" 2>/dev/null | tr ' ' '\n' || true)
    used=$( { compose_ports "${CONTAINER_NAME}"; docker_ports "${CONTAINER_NAME}"; { host_listen_ports | grep -vxF -f <(echo "$own"; echo 0) || true; }; } | sort -un)

    # Port lama dipakai lagi bila masih di dalam rentang dan tidak dipakai pihak lain
    if [ -n "$existing_port" ] && [ "$existing_port" -ge "$PORT_RANGE_START" ] && [ "$existing_port" -le "$PORT_RANGE_END" ]; then
        if ! grep -qx "$existing_port" <<< "$used"; then
            echo "$existing_port"
            return 0
        fi
        log_warn "Port ${existing_port} kini dipakai pihak lain; ${CONTAINER_NAME} dipindah ke port baru"
    fi

    local port
    for port in $(seq "$PORT_RANGE_START" "$PORT_RANGE_END"); do
        if grep -qx "$port" <<< "$used"; then continue; fi
        echo "$port"
        return 0
    done

    log_error "No available ports in range $PORT_RANGE_START-$PORT_RANGE_END"
    exit 1
}

# ==========================================
# Rewrite Logic Functions
# ==========================================

update_cloudflare_config() {
    local container_target=$1
    local internal_port=$2

    log_info "Updating Cloudflare Config for: $FULL_HOSTNAME"

    if [ ! -f "${CLOUDFLARED_CONFIG}" ]; then
        log_error "Cloudflare config not found at ${CLOUDFLARED_CONFIG}"
        exit 1
    fi

    # 1. Hapus Entry Lama. Hostname di-escape dan dicocokkan utuh: tanpa itu titik cocok dengan karakter apa pun
    #    dan entri project lain yang hanya memuat nama ini (mis. mydb.iimlab.id) ikut terhapus.
    local host_re="${FULL_HOSTNAME//./\\.}"
    sed -i -E "/^[[:space:]]*-[[:space:]]+hostname:[[:space:]]+${host_re}[[:space:]]*$/,+1d" ${CLOUDFLARED_CONFIG}

    # 2. Generate Entry Baru (Insert sebelum catch-all rule)
    local new_entry="  - hostname: ${FULL_HOSTNAME}\n    service: http://${container_target}:${internal_port}"

    awk -v entry="$new_entry" '
        /service: http_status:404/ {
            print entry
            print $0
            next
        }
        {print}
    ' ${CLOUDFLARED_CONFIG} > ${CLOUDFLARED_CONFIG}.tmp && mv ${CLOUDFLARED_CONFIG}.tmp ${CLOUDFLARED_CONFIG}
}

# cloudflared hanya membaca config.yml saat start, dan satu tunnel bisa punya beberapa connector (mis. prod_tunnel
# dan prod_tunnel-r2) yang dibagi rata oleh Cloudflare. Connector yang tidak di-restart tetap memakai config lama dan
# menjawab 404 untuk hostname baru. Jadi semua container yang me-mount direktori config ini di-restart bergantian,
# supaya selalu ada connector yang melayani.
restart_tunnel_connectors() {
    local ids id name
    ids=$(docker ps -q | xargs -r docker inspect -f '{{.Id}} {{range .Mounts}}{{.Source}} {{end}}' |
        awk -v d="${CLOUDFLARED_DIR}" '{ for (i = 2; i <= NF; i++) if ($i == d || index($i, d "/") == 1) { print $1; break } }')
    if [ -z "$ids" ]; then
        log_warn "Tidak ada connector yang me-mount ${CLOUDFLARED_DIR}; restart service ${TUNNEL_SERVICE_NAME} saja"
        docker compose restart ${TUNNEL_SERVICE_NAME}
        return
    fi
    for id in $ids; do
        name=$(docker inspect -f '{{.Name}}' "$id" | sed 's#^/##')
        log_info "Restarting tunnel connector: ${name}"
        docker restart "$id" > /dev/null
        # Beri waktu connector mendaftar ulang ke Cloudflare sebelum connector berikutnya dimatikan
        sleep 10
    done
}

# Tulis/ganti blok service di docker-compose.yml bersama milik environment (logika Python dari template)
update_docker_compose() {
    local port=$1
    local internal_port=$2
    local backup_dir=$3

    log_info "Updating Docker Compose for: $CONTAINER_NAME on port $port"

    # Rahasia TIDAK ditulis di sini (file ini dipakai bersama banyak project); semuanya di env_file privat.
    # host.docker.internal → server itu sendiri, tempat instance database bare-metal berjalan.
    export SERVICE_BLOCK="
  ${CONTAINER_NAME}:
    image: ${IMAGE_NAME}
    container_name: ${CONTAINER_NAME}
    restart: unless-stopped
    env_file:
      - ./configs/.env.${CONTAINER_NAME}
    environment:
      PUBLIC_URL: \"https://${FULL_HOSTNAME}\"
      TRUST_PROXY: \"true\"
      COOKIE_SECURE: \"true\"
      TENANT_PREFIX: \"${TENANT_PREFIX}\"
      CI_VARIABLES_ENABLED: \"${CI_VARIABLES_ENABLED}\"
    extra_hosts:
      - \"host.docker.internal:host-gateway\"${GITLAB_EXTRA_HOST:+
      - \"${GITLAB_EXTRA_HOST}\"}${CONTAINER_DNS_BLOCK}
    networks:
      - ${DEPLOY_ENV}_network
    ports:
      - \"${port}:${internal_port}\"
    volumes:
      - ./data/${CONTAINER_NAME}:/data
      - ${backup_dir}:/backups"

    # Python Script: Safe YAML Insert
    python3 -c "
import os

file_path = '${DOCKER_COMPOSE_FILE}'
target_service = '  ${CONTAINER_NAME}:'
new_block = os.environ['SERVICE_BLOCK']

# Initial content if file doesn't exist
default_content = ['version: \"3.8\"\\n', 'services:\\n', 'networks:\\n', '  ${DEPLOY_ENV}_network:\\n', '    external: true\\n']

try:
    with open(file_path, 'r') as f:
        lines = f.readlines()
        if not lines: lines = default_content
except FileNotFoundError:
    lines = default_content

output_lines = []
skip = False
networks_index = -1

# 1. READ & CLEANUP OLD SERVICE
for i, line in enumerate(lines):
    if line.strip().startswith('networks:') and not line.startswith(' '):
        networks_index = len(output_lines)

    if line.startswith(target_service):
        skip = True
        continue

    if skip:
        stripped = line.strip()
        if not stripped: continue
        # Stop skip jika ketemu root key atau service lain
        if line[0] != ' ' and line[0] != '#':
            skip = False
        elif line.startswith('  ') and not line.startswith('    '):
            skip = False
        if skip: continue

    output_lines.append(line)

# 2. INSERT NEW SERVICE (sebelum blok networks root)
if networks_index != -1:
    output_lines.insert(networks_index, new_block.lstrip('\\n') + '\\n')
else:
    output_lines.append(new_block + '\\n')

# 3. WRITE BACK
with open(file_path, 'w') as f:
    f.writelines(output_lines)
"
}

