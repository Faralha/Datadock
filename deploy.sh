build_image() {
    log_info "Building Docker Image: ${IMAGE_NAME}"

    # Berbeda dari template: image lama TIDAK dihapus di sini, supaya rollback ke tag sebelumnya tetap
    # mungkin dan container yang sedang berjalan tidak kehilangan image-nya. Pembersihan lewat job cleanup_images.
    docker build --no-cache --target runtime \
        --build-arg ENV=${DEPLOY_ENV} \
        --build-arg BUILD_DATE=$(date -u +'%Y-%m-%dT%H:%M:%SZ') \
        --build-arg VCS_REF=${CI_COMMIT_SHORT_SHA:-latest} \
        -t ${IMAGE_NAME} \
        -t ${PROJECT_NAME}:${DEPLOY_ENV}-latest \
        -f ${APP_DIR}/Dockerfile ${APP_DIR}
}

wait_healthy() {
    local port=$1
    log_info "Waiting for /health on port ${port}"
    for i in $(seq 1 30); do
        if curl -fsS "http://127.0.0.1:${port}/health" > /dev/null 2>&1; then
            log_info "Control plane healthy (ketiga instance database terjangkau)"
            return 0
        fi
        sleep 2
    done
    log_error "Control plane tidak sehat setelah 60 detik. /health dan log terakhir:"
    curl -sS "http://127.0.0.1:${port}/health" >&2 || true
    docker logs --tail 50 ${CONTAINER_NAME} >&2 || true
    exit 1
}

deploy_app() {
    resolve_environment
    if [ -z "$TUNNEL_ID" ]; then
        log_error "TUNNEL_ID is empty! Please check GitLab CI/CD Variables."
        exit 1
    fi
    log_info "Starting Deployment for $CONTAINER_NAME"

    mkdir -p "${CONFIG_DIR}" "${DATA_DIR}"

    # 1. Siapkan File ENV
    install_app_env
    local backup_root
    backup_root=$(env_get "${APP_ENV_FILE}" BACKUP_HOST_DIR)
    BACKUP_DIR_HOST="${backup_root:-${ENV_DIR}/backups}/${CONTAINER_NAME}"
    mkdir -p "${BACKUP_DIR_HOST}"

    # GITLAB_HOST_IP (opsional): alamat GitLab dilihat dari container, mis. `host-gateway` bila GitLab berjalan di
    # server ini dan namanya di-resolve ke 127.0.0.1 (yang di dalam container berarti container itu sendiri)
    local gitlab_ip gitlab_host
    gitlab_ip=$(env_get "${APP_ENV_FILE}" GITLAB_HOST_IP)
    GITLAB_EXTRA_HOST=""
    if [ -n "$gitlab_ip" ]; then
        gitlab_host=$(env_get "${APP_ENV_FILE}" GITLAB_URL | sed -E 's#^[a-z]+://##; s#[:/].*$##')
        GITLAB_EXTRA_HOST="${gitlab_host}:${gitlab_ip}"
        log_info "GitLab dari container: ${GITLAB_EXTRA_HOST}"
    fi

    # CONTAINER_DNS (opsional, dipisah koma): resolver DNS container, mis. 1.1.1.1 supaya GitLab dihubungi lewat
    # alamat publiknya (Cloudflare, sertifikat valid) dan bukan entri lokal server yang menunjuk ke 127.0.0.1
    local dns_list d
    dns_list=$(env_get "${APP_ENV_FILE}" CONTAINER_DNS)
    CONTAINER_DNS_BLOCK=""
    if [ -n "$dns_list" ]; then
        CONTAINER_DNS_BLOCK=$'\n    dns:'
        for d in ${dns_list//,/ }; do CONTAINER_DNS_BLOCK+=$'\n      - '"$d"; done
        log_info "DNS container: ${dns_list}"
    fi

    # 2. Akun admin hak minimum di instance database yang sudah ada
    bootstrap_admin_accounts

    # 3. Resolve Port & Internal Port
    PORT=$(get_assigned_port)
    INTERNAL_PORT="${INTERNAL_PORT:-3000}"
    log_info "Resolved Host Port: $PORT (internal $INTERNAL_PORT), backups: $BACKUP_DIR_HOST"

    # 4. Update Configuration Files
    update_cloudflare_config "${CONTAINER_NAME}" "${INTERNAL_PORT}"
    update_docker_compose "${PORT}" "${INTERNAL_PORT}" "${BACKUP_DIR_HOST}"

    # 5. Register DNS (Tunnel ID from Env Var)
    log_info "Registering DNS..."
    docker run --rm \
        -v ${CLOUDFLARED_DIR}:/home/nonroot/.cloudflared \
        ${CLOUDFLARED_TUNNEL_IMAGE} \
        tunnel route dns -f ${TUNNEL_ID} ${FULL_HOSTNAME} > /dev/null 2>&1 || true

    # 6. Redeploy Container
    log_info "Recreating Container..."
    docker stop ${CONTAINER_NAME} 2>/dev/null || true
    docker rm ${CONTAINER_NAME} 2>/dev/null || true

    # Metadata SQLite di-backup saat container berhenti (konsisten), 5 cadangan terakhir disimpan.
    # Direktori data & backup milik uid 1000 (user `bun` di image): diatur lewat container karena runner bukan root.
    docker run --rm --user 0 --entrypoint sh -v "${DATA_DIR}:/data" -v "${BACKUP_DIR_HOST}:/backups" ${IMAGE_NAME} -c "
        chown 1000:1000 /data /backups
        if [ -f /data/datadock.sqlite ]; then
            mkdir -p /data/predeploy
            tar -C /data -czf /data/predeploy/datadock-\$(date -u +%Y%m%dT%H%M%SZ)-${IMAGE_TAG}.tgz \$(cd /data && ls datadock.sqlite*)
            ls -1t /data/predeploy/*.tgz | tail -n +6 | xargs -r rm -f
        fi"

    cd ${ENV_DIR}
    docker compose up -d ${CONTAINER_NAME}

    # 7. Restart Tunnel (semua connector/replika yang memakai config ini)
    restart_tunnel_connectors

    wait_healthy "${PORT}"

    echo ""
    echo "🎉 Deployment Success!"
    echo "🌍 URL: https://${FULL_HOSTNAME}"
    echo "🗄️  Tenant prefix: '${TENANT_PREFIX:-<none>}', CI variables: ${CI_VARIABLES_ENABLED}"
}

# ==========================================
# Test (CI): engine sementara di container (versi sama dengan server) + test terhadap engine asli
# ==========================================

test_compose() {
    docker compose -p "${TEST_STACK}" -f "${TEST_ENGINES_COMPOSE}" "$@"
}

# Engine test ada di network `bridge` bawaan (tanpa DNS nama container), jadi dihubungi lewat IP
bridge_ip() {
    local ip
    ip=$(docker inspect -f '{{.NetworkSettings.Networks.bridge.IPAddress}}' "$1")
    [ -n "$ip" ] || { log_error "Container $1 tidak punya IP di network bridge"; exit 1; }
    echo "$ip"
}

run_tests() {
    log_info "Starting temporary engines: ${TEST_STACK}"
    local pg_root mariadb_root mongo_root pg_admin mariadb_admin mongo_admin
    pg_root=$(random_secret); mariadb_root=$(random_secret); mongo_root=$(random_secret)
    pg_admin=$(random_secret); mariadb_admin=$(random_secret); mongo_admin=$(random_secret)

    STACK_NAME="${TEST_STACK}" PG_ROOT_PASSWORD="$pg_root" MARIADB_ROOT_PASSWORD="$mariadb_root" MONGO_ROOT_PASSWORD="$mongo_root" \
        test_compose up -d --wait
    local pg_ip mariadb_ip mongo_ip
    pg_ip=$(bridge_ip "${TEST_STACK}-pg")
    mariadb_ip=$(bridge_ip "${TEST_STACK}-mariadb")
    mongo_ip=$(bridge_ip "${TEST_STACK}-mongo")

    log_info "Building test image"
    docker build --target test -t "${PROJECT_NAME}-test:${IMAGE_TAG}" -f ${APP_DIR}/Dockerfile ${APP_DIR}

    log_info "Running tests"
    mkdir -p coverage
    local tmp
    tmp=$(mktemp)
    chmod 600 "$tmp"
    cat > "$tmp" <<EOF
PG_ROOT_URL=postgres://postgres:${pg_root}@${pg_ip}:5432/postgres
MARIADB_ROOT_URL=mysql://root:${mariadb_root}@${mariadb_ip}:3306
MONGO_ROOT_URL=mongodb://root:${mongo_root}@${mongo_ip}:27017/?authSource=admin
PG_ADMIN_URL=postgres://dbaas_admin:${pg_admin}@${pg_ip}:5432/postgres
MARIADB_ADMIN_URL=mysql://dbaas_admin:${mariadb_admin}@${mariadb_ip}:3306
MONGO_ADMIN_URL=mongodb://dbaas_admin:${mongo_admin}@${mongo_ip}:27017/?authSource=admin
EOF
    local status=0
    docker run --rm --network bridge --env-file "$tmp" \
        -v "$(pwd)/coverage:/app/coverage" \
        "${PROJECT_NAME}-test:${IMAGE_TAG}" \
        sh -c '
            bun test --timeout 60000 --coverage --coverage-reporter=lcov --coverage-reporter=text --coverage-dir=coverage test/
            status=$?
            # Path di lcov relatif ke control-plane/; SonarQube membaca dari root repo
            [ -f coverage/lcov.info ] && sed -i "s#^SF:#SF:control-plane/#" coverage/lcov.info
            # Container berjalan sebagai root: buka izin supaya runner dan job Sonar (bukan root) bisa membaca artifact
            chmod -R a+rwX coverage
            exit $status' || status=$?
    rm -f "$tmp"
    return $status
}

test_cleanup() {
    log_info "Removing temporary engines: ${TEST_STACK}"
    STACK_NAME="${TEST_STACK}" PG_ROOT_PASSWORD=x MARIADB_ROOT_PASSWORD=x MONGO_ROOT_PASSWORD=x \
        test_compose down -v --remove-orphans || true
    docker rmi "${PROJECT_NAME}-test:${IMAGE_TAG}" 2>/dev/null || true
}

