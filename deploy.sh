# CI/CD variable berisi env file bisa bertipe File (nilainya path) atau Variable (nilainya isi file).
# Mencetak path salinan sementara (chmod 600, hapus setelah dipakai) yang sudah dinormalkan untuk
# `docker run --env-file`, yang tidak membuang CR, awalan `export`, maupun tanda kutip di sekitar nilai.
ci_env_file() {
    local name=$1 value=${!1}
    [ -n "$value" ] || return 0
    local tmp
    tmp=$(mktemp)
    chmod 600 "$tmp"
    if [ -f "$value" ]; then
        cat "$value" > "$tmp"
    else
        printf '%s\n' "$value" > "$tmp"
        log_warn "$name bertipe Variable (bukan File): isinya dipakai sebagai env file"
    fi
    sed -i -E \
        -e 's/\r$//' \
        -e 's/^[[:space:]]*(export[[:space:]]+)?//' \
        -e "s/^([A-Za-z_][A-Za-z0-9_]*)=\"(.*)\"[[:space:]]*$/\1=\2/" \
        -e "s/^([A-Za-z_][A-Za-z0-9_]*)='(.*)'[[:space:]]*$/\1=\2/" \
        "$tmp"
    echo "$tmp"
}

# Awalan env per engine yang diaktifkan (ENGINES di env file control plane; default semua engine)
engine_prefixes() {
    local list e
    list=$(grep -E '^ENGINES=' "$1" | tail -1 | cut -d= -f2- | tr ',' ' ')
    for e in ${list:-postgres mariadb mongo}; do
        case "$e" in
            postgres) echo PG ;;
            mariadb) echo MARIADB ;;
            mongo) echo MONGO ;;
            *) log_error "ENGINES berisi engine tidak dikenal: $e (pilihan: postgres, mariadb, mongo)"; exit 1 ;;
        esac
    done
}

# Hentikan deploy bila key wajib tidak ada di env file. Yang dicetak hanya nama key, tidak pernah nilainya.
require_env_keys() {
    local name=$1 file=$2 missing=() k
    shift 2
    for k in "$@"; do
        grep -qE "^${k}=.+" "$file" || missing+=("$k")
    done
    [ ${#missing[@]} -eq 0 ] && return 0
    log_error "$name tidak berisi: ${missing[*]}
   Key yang ditemukan: $(grep -oE '^[A-Za-z_][A-Za-z0-9_]*=' "$file" | tr -d '=' | tr '\n' ' ')
   Lihat contoh di deploy/app.env.example dan deploy/root.env.example."
    rm -f "$file"
    exit 1
}

# Env file control plane disalin dari CI/CD variable DATADOCK_ENV_FILE bila ada; kalau tidak, file yang sudah
# ada di server dipakai. Tanpa keduanya deploy dihentikan (template membuat file kosong, tapi control plane
# tidak bisa jalan tanpa konfigurasi).
install_app_env() {
    local src
    src=$(ci_env_file DATADOCK_ENV_FILE)
    if [ -n "$src" ]; then
        local prefixes
        prefixes=$(engine_prefixes "$src") || { rm -f "$src"; exit 1; }
        # shellcheck disable=SC2046
        require_env_keys DATADOCK_ENV_FILE "$src" ENCRYPTION_KEY GITLAB_URL GITLAB_CLIENT_ID GITLAB_CLIENT_SECRET \
            GITLAB_BOT_TOKEN $(for p in $prefixes; do echo "${p}_ADMIN_PASSWORD"; done)
        install -m 600 "$src" "$APP_ENV_FILE"
        rm -f "$src"
        log_info "Env control plane diperbarui dari CI/CD variable"
    elif [ -f "$APP_ENV_FILE" ]; then
        log_info "Env control plane memakai file yang sudah ada: $APP_ENV_FILE"
    else
        log_error "Env control plane tidak ditemukan: CI/CD variable DATADOCK_ENV_FILE tidak sampai ke job ini, dan $APP_ENV_FILE belum ada di server.
   Periksa di Settings > CI/CD > Variables:
   - nama persis DATADOCK_ENV_FILE
   - Environment scope: production atau * (job ini: environment '${CI_ENVIRONMENT_NAME:-?}')
   - bila Protected: branch '${CI_COMMIT_BRANCH:-?}' harus protected (Settings > Repository > Protected branches)"
        exit 1
    fi
}

# Buat/selaraskan akun admin hak minimum di instance database yang sudah ada (idempoten), memakai akun root
# dari CI/CD variable bertipe File DATADOCK_ROOT_ENV_FILE. File itu dibaca langsung dari workspace job:
# tidak disalin ke server dan tidak masuk ke container control plane.
bootstrap_admin_accounts() {
    local root_env status=0
    root_env=$(ci_env_file DATADOCK_ROOT_ENV_FILE)
    if [ -z "$root_env" ]; then
        log_warn "DATADOCK_ROOT_ENV_FILE tidak diisi: bootstrap akun admin dilewati (akun dbaas_admin dianggap sudah ada)."
        return 0
    fi
    local prefixes
    prefixes=$(engine_prefixes "$APP_ENV_FILE") || { rm -f "$root_env"; exit 1; }
    # shellcheck disable=SC2046
    require_env_keys DATADOCK_ROOT_ENV_FILE "$root_env" $(for p in $prefixes; do echo "${p}_ROOT_URL"; done)
    log_info "Bootstrapping least-privilege admin accounts on existing database instances"
    docker run --rm --add-host host.docker.internal:host-gateway \
        --env-file "${APP_ENV_FILE}" --env-file "${root_env}" \
        --entrypoint bun "${IMAGE_NAME}" src/bootstrap.ts || status=$?
    rm -f "$root_env"
    return $status
}

