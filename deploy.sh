case "${1}" in
    build) build_image ;;
    deploy) deploy_app ;;
    test) run_tests ;;
    test-cleanup) test_cleanup ;;
    *) echo "Usage: $0 {build|deploy|test|test-cleanup}"; exit 1 ;;
esac
